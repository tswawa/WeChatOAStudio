// 验证首次快捷语句迁移按账号独立执行，删除和重启都不会使默认项复活。
const { test } = require('node:test')
const assert = require('node:assert/strict')
const { mkdtempSync, rmSync } = require('node:fs')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { createOpsStore } = require('./store.cjs')
const { initializeShortcuts, DEFAULT_SHORTCUTS } = require('./shortcuts.cjs')

test('default shortcuts initialize once and deletion survives restart', (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'mp-shortcuts-'))
  const filename = join(directory, 'ops.sqlite')
  let store = createOpsStore(filename)
  t.after(() => { store.close(); rmSync(directory, { recursive: true, force: true }) })
  assert.equal(initializeShortcuts(store, 'a'), true)
  assert.deepEqual(store.list('shortcuts', 'a').map((item) => item.content), DEFAULT_SHORTCUTS)
  for (const item of store.list('shortcuts', 'a')) store.remove('shortcuts', 'a', item.id)
  store.close()
  store = createOpsStore(filename)
  assert.equal(initializeShortcuts(store, 'a'), false)
  assert.deepEqual(store.list('shortcuts', 'a'), [])
  assert.equal(initializeShortcuts(store, 'b'), true)
  assert.equal(store.list('shortcuts', 'b').length, 6)
})
